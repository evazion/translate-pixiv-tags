export function getSitePriority(siteName: string) {
    const priority = SITE_ORDER.indexOf(siteName);
    return priority < 0 ? 1000 : priority;
}

export function getSiteName(siteUrl: string) {
    const { hostname, pathname } = new URL(siteUrl);
    const url = parse(hostname);
    if ("error" in url) throw new Error(url.error.message + "");

    const match = SITE_RULES.find(
        (rule) =>
            (rule.hostname || rule.domain || rule.tld || rule.pathname) &&
            (!rule.hostname || rule.hostname === hostname) &&
            (!rule.domain || rule.domain === url.domain) &&
            (!rule.tld || rule.tld === url.tld) &&
            (!rule.pathname || pathname.includes(rule.pathname)),
    );

    return match ? match.name : capitalize(url.sld || url.tld || hostname);
}

export function getSiteDisplayDomain(siteUrl: string) {
    const { hostname } = new URL(siteUrl);
    const url = parse(hostname);
    if ("error" in url) throw new Error(url.error.message + "");
    return url.domain || url.tld || hostname;
}

const SITE_ICON_FOLDER =
    "https://raw.githubusercontent.com/danbooru/danbooru/22e1b4d3bf0a8776dbac282f4e3a83d62facc537/public/images/";

/** Try to resolve the site icon */
function getSiteIconUrl_(siteName: string, url: string): Promise<string | null> {
    if (SITE_RULES.every((site) => site.name !== siteName)) {
        return new Promise((resolve) => {
            GM.xmlHttpRequest({
                method: "GET",
                url: `https://icons.duckduckgo.com/ip3/${new URL(url).hostname}.ico`,
                responseType: "blob",
                onload: (xhr) => {
                    // for unresolved icons the response is 404 + fallback icon
                    if (xhr.status === 200) {
                        resolve(window.URL.createObjectURL(xhr.response));
                    } else {
                        resolve(null);
                    }
                },
            });
        });
    }
    const fileName = siteName.toLowerCase().replaceAll(/[^\w.]/g, "-");
    return getImage(`${SITE_ICON_FOLDER}${fileName}-logo.png`);
}

export const getSiteIconUrl = memoize(getSiteIconUrl_, memoizeKey);

